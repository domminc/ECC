function parseCsv(text) {
  const src = text.replace(/^﻿/, '');
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (quoted) {
      if (ch === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          quoted = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && src[i + 1] === '\n') i++;
      row.push(field);
      field = '';
      rows.push(row);
      row = [];
    } else {
      field += ch;
    }
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter(r => r.some(cell => cell.trim() !== ''));
}

function agencyKey(name) {
  const key = Object.keys(AGENCIES).find(k => name.startsWith(k));
  if (!key) throw new Error(`Unknown agency: ${name}`);
  return key;
}

function buildData(csvText) {
  const [header, ...rows] = parseCsv(csvText);
  if (header.length !== 12) {
    throw new Error(`Expected 12 columns, got ${header.length}`);
  }
  const counters = {};
  const funds = rows.map(cols => {
    const [agencyName, group, name, conditions, limit, rate, term, method, docs, pages, noticeUrl, pdfUrl] =
      cols.map(c => c.trim());
    const key = agencyKey(agencyName);
    const agency = AGENCIES[key];
    counters[agency.id] = (counters[agency.id] || 0) + 1;

    const targets = [...agency.defaultTargets];
    if (/소상공인 포함 가능/.test(conditions) && !targets.includes('소상공인')) {
      targets.push('소상공인');
    }

    return {
      id: `${agency.id}-${String(counters[agency.id]).padStart(2, '0')}`,
      agency: agency.short,
      agencyFull: agencyName,
      group,
      name,
      targets,
      conditions,
      limit,
      rate,
      term,
      method,
      documents: [],
      documentsNote: docs,
      unconfirmed: {
        limit: UNCONFIRMED.test(limit) || limit === '-',
        rate: UNCONFIRMED.test(rate) || rate === '-',
        term: UNCONFIRMED.test(term) || term === '-'
      },
      forms: [],
      pages,
      noticeUrl,
      pdfUrl
    };
  });
  return { meta: META, funds };
}

function writeOutputs() {
  const data = buildData(fs.readFileSync(CSV_PATH, 'utf8'));
  const json = JSON.stringify(data, null, 2);
  fs.writeFileSync(JSON_PATH, `${json}\n`);
  fs.writeFileSync(
    JS_PATH,
    `// Generated by tools/build-data.js from policy_funds_2026.csv. Do not edit.\nwindow.POLICY_FUND_DATA = ${json};\n`
  );
  return data;
}

if (require.main === module) {
  const data = writeOutputs();
  console.log(`Wrote ${data.funds.length} funds to ${path.relative(process.cwd(), JSON_PATH)}`);
}

module.exports = { parseCsv, buildData, META, CSV_PATH, JSON_PATH, JS_PATH };
